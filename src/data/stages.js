// 依照目前路線位置取得下一個場景 id
// route: { bound: 'west'|'east'|null, col: -1..3, row }
export function nextOptions(route) {
  if (!route.bound) return { left: { bound: 'west', col: 0, row: 0 }, right: { bound: 'east', col: 0, row: 0 } };
  if (route.col >= 3) return null;
  return {
    left: { bound: route.bound, col: route.col + 1, row: route.row },
    right: { bound: route.bound, col: route.col + 1, row: route.row + 1 },
  };
}

export function stageIdOf(route) {
  if (!route.bound) return START_STAGE;
  return ROUTES[route.bound][route.col][route.row];
}

